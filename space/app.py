"""Live demo for the IPC/BNS retrieval-augmented legal assistant.

A visitor needs nothing: no key, no install, no clone. Retrieval runs entirely
inside the Space on a local embedding model; answer generation uses the Space
owner's HF_TOKEN if one is set, and the app degrades to showing the retrieved
statute text when it is not.
"""

import os

import streamlit as st

import rag

PAPER_URL = "https://doi.org/10.1007/s42454-025-00086-8"
MAX_QUERIES_PER_SESSION = 25

EXAMPLES = [
    "What is the punishment for criminal breach of trust?",
    "How does the BNS define theft?",
    "What counts as culpable homicide not amounting to murder?",
    "Is cheating by personation a separate offence?",
    "What are the ingredients of criminal conspiracy?",
]

st.set_page_config(
    page_title="Indian Law RAG — IPC + BNS",
    page_icon="⚖️",
    layout="centered",
)


@st.cache_resource(show_spinner="Loading the IPC + BNS index…")
def get_store():
    return rag.load_retriever()


def token():
    return os.environ.get("HF_TOKEN") or os.environ.get("HUGGINGFACEHUB_API_TOKEN")


def render_sources(passages):
    st.markdown("#### Retrieved statute text")
    st.caption(
        "The passages the answer was built from, BNS first. Every answer above is "
        "grounded in exactly these — nothing else was in the model's context."
    )
    for i, p in enumerate(passages, 1):
        label = f"[{i}] {p.statute} — {p.citation}"
        with st.expander(label):
            st.text(p.text.strip())


def main():
    st.title("⚖️ Indian Law RAG — IPC + BNS")
    st.markdown(
        "Ask a plain-language question about Indian criminal law. Answers are drawn "
        "only from the **Bharatiya Nyaya Sanhita** and the **Indian Penal Code**, "
        "with the BNS given priority as the statute now in force, and every claim "
        "cited back to a page of the source document.\n\n"
        f"Reference implementation for [*Redefining legal access: a RAG-based AI "
        f"system for Indian law*]({PAPER_URL}), Human-Intelligent Systems "
        "Integration 7(1), 2025."
    )

    st.session_state.setdefault("query_count", 0)
    st.session_state.setdefault("question", "")

    st.markdown("**Try one of these:**")
    columns = st.columns(len(EXAMPLES[:3]))
    for column, example in zip(columns, EXAMPLES[:3]):
        if column.button(example, width="stretch"):
            st.session_state["question"] = example
    with st.expander("More example questions"):
        for example in EXAMPLES[3:]:
            if st.button(example, key=f"ex-{example}", width="stretch"):
                st.session_state["question"] = example

    question = rag.clean_question(
        st.text_input(
            "Your question",
            value=st.session_state["question"],
            placeholder="e.g. What is the punishment for criminal breach of trust?",
        )
    )

    if not question:
        st.stop()

    if st.session_state["query_count"] >= MAX_QUERIES_PER_SESSION:
        st.warning(
            "Session limit reached. Reload the page to continue — the cap keeps the "
            "demo's hosted inference budget available for everyone."
        )
        st.stop()

    try:
        store = get_store()
    except Exception as exc:
        st.error(f"The index could not be opened: {exc}")
        st.stop()

    with st.spinner("Searching the IPC and BNS…"):
        passages = rag.retrieve(store, question)

    if not passages:
        st.info("Nothing in the IPC or BNS matched that question.")
        st.stop()

    api_token = token()
    if api_token:
        st.session_state["query_count"] += 1
        with st.spinner("Reading the retrieved sections…"):
            try:
                answer, model = rag.generate(question, passages, api_token)
                st.markdown("#### Answer")
                st.markdown(answer)
                st.caption(f"Generated by `{model}` from the passages below.")
            except Exception as exc:
                st.warning(
                    "The language model is unavailable right now, so this is "
                    "retrieval only — the statute text below is what the system "
                    "found for your question."
                )
                st.caption(str(exc).splitlines()[0])
    else:
        st.info(
            "Running in **retrieval-only** mode: no generation token is configured "
            "on this Space, so the app shows the statute passages it retrieved "
            "rather than a written answer."
        )

    render_sources(passages)

    st.divider()
    st.caption(
        "Research prototype, not legal advice. Outputs are not a substitute for a "
        "qualified advocate. The BNS and IPC texts are published legal documents; "
        "rights remain with their respective publishers."
    )


if __name__ == "__main__":
    main()
